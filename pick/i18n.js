  // 代币名本地化（四站共用一份语言包的关键）
  // 语言包里所有 "TKCC" 都是"本应用的抽奖代币"占位符，按 config.tokenName
  // 整体替换即可 —— 四个站点（TKCC / ORION / PICK / LEO）不需要在 40 处
  // 调用点逐个传参，也不必各维护一份语言包。
  // 只替换大写 "TKCC"：`tkccToken`（config 字段名）、`TkccNotConfigured`
  //（合约错误名）这类混合/小写标识符不受影响。
  // ---------------------------------------------------------------------
  (function localizeTokenName() {
    const sym = (window.CJ_CONFIG && window.CJ_CONFIG.tokenName) || 'TKCC';
    if (!sym || sym === 'TKCC') return;
    LANGS.forEach((lg) => {
      const d = DICT[lg];
      if (!d) return;
      Object.keys(d).forEach((k) => {
        if (typeof d[k] === 'string' && d[k].indexOf('TKCC') >= 0) {
          d[k] = d[k].split('TKCC').join(sym);
        }
      });
    });
  })();

  let lang = loadLang();

  function loadLang() {
    try {
      const v = localStorage.getItem(KEY);
      if (LANGS.indexOf(v) >= 0) return v;
    } catch (_) {}
    const nav = (navigator.language || '').toLowerCase();
    return nav.indexOf('zh') === 0 ? 'zh' : 'en';
  }

  function t(key, params) {
    let s = (DICT[lang] && DICT[lang][key]) || (DICT.zh && DICT.zh[key]);
    if (s == null) return key;
    if (params) {
      Object.keys(params).forEach((k) => {
        s = s.split('{' + k + '}').join(params[k]);
      });
    }
    return s;
  }

  /** 把静态 DOM 上的 data-i18n / data-i18n-placeholder 套用到当前语言 */
